const assert = require('node:assert/strict');
require('./softadmin-project-history.js');
const history = globalThis.SoftadminProjectHistory;
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const makeProject = id => ({ id: String(id), name: `Project ${id}`, state: { rootHtml: '<div></div>' }, revision: `revision-${id}` });
assert.deepEqual(history.read(storage).projects, []);
const legacy = Array.from({ length: 20 }, (_, index) => ({ ...makeProject(index), savedAt: new Date(2026, 0, index + 1).toISOString() }));
storage.setItem(history.legacyKey, JSON.stringify(legacy));
let data = history.read(storage);
assert.equal(data.projects.length, 10);
assert.equal(data.activeId, '19');
assert.equal(data.projects[9].id, '10');
history.write(storage, data);
assert.equal(JSON.parse(storage.getItem(history.legacyKey)).length, 20);
data = history.upsert(data, makeProject('new'), null);
assert.equal(data.projects.length, 10);
assert.equal(data.projects[0].id, 'new');
const edited = { ...data.projects[5], revision: 'edited' };
data = history.upsert(data, edited, data.projects[5].revision);
assert.equal(data.projects[0].id, edited.id);
assert.equal(data.projects.length, 10);
assert.throws(() => history.upsert(data, { ...edited, revision: 'stale' }, 'old'), /another tab/);
const persisted = storage.getItem(history.key);
assert.throws(() => history.write({ setItem() { throw new Error('quota'); } }, data), /quota/);
assert.equal(storage.getItem(history.key), persisted);
storage.setItem(history.key, '{broken');
assert.throws(() => history.read(storage));
assert.equal(storage.getItem(history.key), '{broken');
console.log('Passed project history: migration, retention, recency, revisions, quota and corrupt-data protection.');
