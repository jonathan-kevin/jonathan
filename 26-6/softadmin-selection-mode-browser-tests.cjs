const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
	const browser = await chromium.launch({ channel: 'msedge', headless: true });
	try {
		const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
		const page = await context.newPage();
		page.setDefaultTimeout(10000);
		const errors = [];
		page.on('pageerror', error => errors.push(error.message));
		const requests = [];
		await context.route('**/.netlify/functions/softadmin-spec', async route => {
			const request = route.request().postDataJSON();
			requests.push(request);
			await route.fulfill({ json: { spec: request.currentSpec }, headers: { 'access-control-allow-origin': '*' } });
		});
		await page.goto(process.env.SOFTADMIN_TEST_URL || 'http://localhost/jonathan-git/26-6/');
		const mode = value => page.locator('#SoftadminComponentSelectionMode label').filter({ has: page.locator(`input[value="${value}"]`) });
		const picker = page.locator('#SoftadminComponentPicker');
		const card = value => picker.locator('label').filter({ has: page.locator(`input[value="${value}"]`) });
		const root = page.locator('[data-softadmin-component-root]');
		const saved = () => page.locator('#SoftadminAutosaveStatus[data-state="saved"]').waitFor();
		assert.equal(await picker.isVisible(), false);
		assert.equal(await picker.locator('input[value=""]').count(), 0);
		assert.equal(await page.locator('#SoftadminGenerate').isEnabled(), true);
		await mode('manual').click();
		assert.equal(await picker.isVisible(), true);
		assert.equal(await page.locator('#SoftadminGenerate').isDisabled(), true);
		await card('NewEdit').click();
		await page.locator('[data-softadmin-field-id]').first().waitFor();
		assert.equal(await page.locator('#SoftadminGenerate').isEnabled(), true);
		const formHtml = await root.innerHTML();
		await mode('ai').click();
		assert.equal(await picker.isVisible(), false);
		assert.equal(await root.innerHTML(), formHtml, 'Mode changes must not replace the mockup.');
		await page.locator('#SoftadminUndo').click();
		assert.equal(await picker.isVisible(), true);
		await page.locator('#SoftadminRedo').click();
		assert.equal(await picker.isVisible(), false);
		await saved();
		await page.reload();
		await saved();
		assert.equal(await picker.isVisible(), false);
		assert.equal(await picker.locator('input[value="NewEdit"]').isChecked(), true);
		await page.locator('#SoftadminPrompt').fill('Only revise the title');
		await page.locator('#SoftadminGenerate').click();
		await page.waitForFunction(() => !document.getElementById('SoftadminGenerate').disabled);
		assert.equal(requests.length, 1);
		assert.doesNotMatch(requests[0].prompt, /Emit component type/);
		await mode('manual').click();
		assert.equal(await picker.locator('input[value="NewEdit"]').isChecked(), true);
		await page.locator('#SoftadminPrompt').fill('Only revise the title again');
		await page.locator('#SoftadminGenerate').click();
		await page.waitForFunction(() => !document.getElementById('SoftadminGenerate').disabled);
		assert.equal(requests.length, 2);
		assert.match(requests[1].prompt, /Emit component type "NewEdit"/);
		await card('CalendarWeekdays').click();
		assert.equal(await page.locator('#SoftadminCalendarModePicker').isVisible(), true);
		const calendarHtml = await root.innerHTML();
		await mode('ai').click();
		assert.equal(await page.locator('#SoftadminCalendarModePicker').isVisible(), false);
		await mode('manual').click();
		assert.equal(await page.locator('#SoftadminCalendarModePicker').isVisible(), true);
		assert.equal(await root.innerHTML(), calendarHtml);
		await saved();
		await page.reload();
		await saved();
		assert.equal(await picker.isVisible(), true);
		assert.equal(await picker.locator('input[value="CalendarWeekdays"]').isChecked(), true);
		await page.evaluate(() => {
			const key = 'softadmin.mockup.projects.v1';
			const history = JSON.parse(localStorage.getItem(key));
			delete history.projects.find(project => project.id === history.activeId).state.selectionMode;
			localStorage.setItem(key, JSON.stringify(history));
		});
		await page.reload();
		await saved();
		assert.equal(await picker.isVisible(), true, 'Older projects with a chosen component reopen in manual mode.');
		await mode('ai').click();
		await page.locator('[data-softadmin-example-prompt][data-softadmin-component="BankID"]').click();
		assert.equal(await picker.isVisible(), true, 'Examples explicitly select manual mode.');
		assert.equal(await picker.locator('input[value="BankID"]').isChecked(), true);
		await page.locator('#SoftadminLanguagePicker label').filter({ hasText: 'Swedish' }).click();
		assert.match(await mode('manual').innerText(), /Manuellt val/);
		await page.screenshot({ path: require('node:path').join(require('node:os').tmpdir(), 'softadmin-selection-mode-desktop.png') });
		await page.setViewportSize({ width: 390, height: 844 });
		await mode('ai').click();
		await mode('manual').scrollIntoViewIfNeeded();
		const box = await mode('manual').boundingBox();
		assert.ok(box && box.x >= 0 && box.x + box.width <= 390);
		await page.screenshot({ path: require('node:path').join(require('node:os').tmpdir(), 'softadmin-selection-mode-mobile.png') });
		assert.deepEqual(errors, []);
		console.log('Passed selection mode: visibility, prompt instructions, preservation, undo/redo, autosave/reload, examples, calendar, localization and mobile. No Azure calls.');
	} finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
