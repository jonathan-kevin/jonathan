const translatedText = new WeakMap<Text, { source: string; translated: string }>();
const translatedAttributes = new WeakMap<Element, Map<string, { source: string; translated: string }>>();

function translate(value: string) {
  const normalized = value.replace(/\s+/g, " ").trim();
  if (!normalized) return value;
  let translated = english[normalized];
  if (!translated) {
    for (const [pattern, replacement] of patterns) {
      const match = normalized.match(pattern);
      if (match) {
        translated = replacement(...match);
        break;
      }
    }
  }
  if (!translated) return value;
  return `${value.match(/^\s*/)?.[0] ?? ""}${translated}${value.match(/\s*$/)?.[0] ?? ""}`;
}

export function installPublicTranslation(language: Language) {
  const root = document.querySelector(".store-shell");
  if (!root) return () => undefined;
  let scheduled = false;
  const process = () => {
    scheduled = false;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let current: Node | null;
    while ((current = walker.nextNode())) {
      const node = current as Text;
      const parent = node.parentElement;
      if (!parent || parent.closest("[data-no-translate], script, style")) continue;
      const record = translatedText.get(node);
      const value = node.nodeValue ?? "";
      const source = record && (value === record.source || value === record.translated)
        ? record.source
        : value;
      const target = language === "en" ? translate(source) : source;
      translatedText.set(node, { source, translated: translate(source) });
      if (value !== target) node.nodeValue = target;
    }
    root.querySelectorAll("[aria-label], [title], [placeholder]").forEach((element) => {
      if (element.closest("[data-no-translate]")) return;
      const records = translatedAttributes.get(element) ?? new Map();
      for (const name of ["aria-label", "title", "placeholder"]) {
        const value = element.getAttribute(name);
        if (value === null) continue;
        const record = records.get(name);
        const source = record && (value === record.source || value === record.translated)
          ? record.source
          : value;
        const target = language === "en" ? translate(source) : source;
        records.set(name, { source, translated: translate(source) });
        if (value !== target) element.setAttribute(name, target);
      }
      translatedAttributes.set(element, records);
    });
  };
  const observer = new MutationObserver(() => {
    if (scheduled) return;
    scheduled = true;
    queueMicrotask(process);
  });
  process();
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "title", "placeholder"] });
  return () => observer.disconnect();
}
